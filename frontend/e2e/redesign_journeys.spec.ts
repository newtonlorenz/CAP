test('failed upload and failed attachment preserve current evidence and attachment retry does not upload twice', async ({ page }, info) => {
  const f = await fixture(page)
  await page.goto(f.url)
  const question = page.getByRole('article', { name: 'Describe the ownership structure.' })
  await question.getByLabel('Upload evidence for this answer').setInputFiles('e2e/fixtures/test.pdf')
  await question.getByRole('button', { name: 'Upload and attach', exact: true }).click()
  await expect(question.getByText(/test.pdf attached to this answer/)).toBeVisible()
  const oldId = answer(await readForm(page, f.form.id)).evidence_ids[0]
  await question.getByLabel('Attachment action').selectOption(oldId)
  await question.getByLabel('Upload evidence for this answer').setInputFiles({ name: 'replacement.pdf', mimeType: 'application/pdf', buffer: pdfBytes })
  await page.route('**/api/v1/preparation/evidence/upload', route => route.abort('failed'), { times: 1 })
  await question.getByRole('button', { name: 'Upload replacement and attach' }).click()
  await expect(question.getByRole('button', { name: 'Retry upload' })).toBeVisible()
  expect(answer(await readForm(page, f.form.id)).evidence_ids).toEqual([oldId])
  await page.setViewportSize({ width: 390, height: 844 })
  await capture(page, info.outputPath('mobile-upload-interrupted.png'))
  let uploads = 0
  page.on('request', request => { if (request.url().endsWith('/preparation/evidence/upload')) uploads += 1 })
  await page.route(`**/api/v1/preparation/cases/${f.form.id}/responses/ownership`, async route => { if (route.request().method() === 'PUT') await route.fulfill({ status: 503, json: { detail: 'Synthetic attachment failure' } }); else await route.continue() }, { times: 1 })
  await question.getByRole('button', { name: 'Retry upload' }).click()
  await expect(question.getByText(/file uploaded, but was not attached/)).toBeVisible()
  expect(answer(await readForm(page, f.form.id)).evidence_ids).toEqual([oldId])
  await page.getByRole('button', { name: /^(Resume editing|Retry saving)$/ }).click()
  await question.getByRole('button', { name: 'Retry attaching uploaded file' }).click()
  await expect(question.getByText(/replacement.pdf attached to this answer/)).toBeVisible()
  expect(uploads).toBe(1)
  expect(answer(await readForm(page, f.form.id)).evidence_ids).not.toContain(oldId)
})

