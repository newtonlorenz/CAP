test('attachment controls cannot mutate the answer while an upload is held in flight', async ({ page }) => {
  const f = await fixture(page)
  await page.goto(f.url)
  const question = page.getByRole('article', { name: 'Describe the ownership structure.' })
  await question.getByLabel('Upload evidence for this answer').setInputFiles('e2e/fixtures/test.pdf')
  await question.getByRole('button', { name: 'Upload and attach', exact: true }).click()
  await expect(question.getByText(/test.pdf attached to this answer/)).toBeVisible()
  const before = answer(await readForm(page, f.form.id)).evidence_ids
  let release!: () => void
  const held = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/v1/preparation/evidence/upload', async route => { await held; await route.continue() }, { times: 1 })
  await question.getByLabel('Upload evidence for this answer').setInputFiles({ name: 'additional-record.pdf', mimeType: 'application/pdf', buffer: pdfBytes })
  await question.getByRole('button', { name: 'Upload and attach', exact: true }).click()
  await expect(question.getByRole('button', { name: 'Remove test.pdf' })).toBeDisabled()
  await expect(question.getByRole('button', { name: 'Add evidence', exact: true })).toBeDisabled()
  const remote = await readForm(page, f.form.id)
  expect(answer(remote).evidence_ids).toEqual(before)
  await json(await page.request.put(`/api/v1/preparation/cases/${f.form.id}/responses/ownership`, { data: { expected_revision: remote.revision, value: 'Another editor changed the answer during upload.', evidence_ids: before, not_applicable_reason: null } }))
  release()
  await expect(question.getByText(/file uploaded, but was not attached/)).toBeVisible()
  await page.getByRole('button', { name: 'Use latest form for attachment retry' }).click()
  await question.getByRole('button', { name: 'Retry attaching uploaded file' }).click()
  await expect(question.getByText(/additional-record.pdf attached to this answer/)).toBeVisible()
  const saved = answer(await readForm(page, f.form.id))
  expect(saved.evidence_ids).toHaveLength(2); expect(saved.evidence_ids).toContain(before[0])
  expect(saved.value).toBe('Another editor changed the answer during upload.')
})

test('a conflict refresh removes a detached evidence preview before latest answer acceptance', async ({ page }) => {
  const f = await fixture(page)
  const upload = async (name: string) => json(await page.request.post('/api/v1/preparation/evidence/upload', { multipart: { title: name, case_id: f.form.id, file: { name, mimeType: 'application/pdf', buffer: pdfBytes } } }))
  const a = await upload('still-current-A.pdf'), b = await upload('replaced-B.pdf'), c = await upload('replacement-C.pdf')
  let current = await readForm(page, f.form.id)
  current = await json(await page.request.put(`/api/v1/preparation/cases/${f.form.id}/responses/ownership`, { data: { expected_revision: current.revision, value: 'Answer with two attachments.', evidence_ids: [a.id, b.id], not_applicable_reason: null } }))
  await page.goto(`/answer-review?case_filter=${f.form.id}&case=${f.form.id}&field=ownership`)
  const selectedResponse = answer(current)
  const bIndex = selectedResponse.evidence_ids.indexOf(b.id)
  await page.getByLabel('Preview attachment').selectOption(b.id)
  expect(bIndex).toBeGreaterThanOrEqual(0)
  await expect(page.getByRole('region', { name: 'Selected evidence preview' }).getByText('replaced-B.pdf')).toBeVisible()
  await json(await page.request.put(`/api/v1/preparation/cases/${f.form.id}/responses/ownership`, { data: { expected_revision: current.revision, value: 'Answer with current replacement.', evidence_ids: [a.id, c.id], not_applicable_reason: null } }))
  await page.getByRole('button', { name: 'Accept answer & next' }).click()
  await expect(page.getByRole('button', { name: 'I have reviewed the latest answer' })).toBeEnabled()
  await expect(page.getByRole('region', { name: 'Selected evidence preview' }).getByText('replaced-B.pdf')).not.toBeVisible()
  await page.getByLabel('Preview attachment').selectOption(c.id)
  await expect(page.getByRole('region', { name: 'Selected evidence preview' }).getByText('replacement-C.pdf')).toBeVisible()
  await page.getByRole('button', { name: 'I have reviewed the latest answer' }).click()
  await page.getByRole('button', { name: 'Accept answer & next' }).click()
  await expect.poll(async () => answer(await readForm(page, f.form.id)).accepted_at).toBeTruthy()
  expect(answer(await readForm(page, f.form.id)).evidence_ids.sort()).toEqual([a.id, c.id].sort())
})
